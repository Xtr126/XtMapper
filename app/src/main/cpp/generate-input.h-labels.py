"""Generate native input.h labels and Kotlin codes/labels from NDK headers.

Adapted from AOSP toolbox/generate-input.h-labels.py (android16-qpr2-release).
Literal definitions supply canonical labels; aliases remain available as codes.
"""
import argparse
import ast
from pathlib import Path
import re

GROUPS = {
    "input_prop": ("INPUT_PROP_",), "ev": ("EV_",), "syn": ("SYN_",),
    "key": ("KEY_", "BTN_"), "rel": ("REL_",), "abs": ("ABS_",),
    "sw": ("SW_",), "msc": ("MSC_",), "led": ("LED_",),
    "rep": ("REP_",), "snd": ("SND_",), "mt_tool": ("MT_TOOL_",),
    "ff_status": ("FF_STATUS_",), "ff": ("FF_",),
}
DEFINE = re.compile(r"^#define\s+(\w+)\s+(.+)$")
LITERAL = re.compile(r"(?:0[xX][0-9a-fA-F]+|[0-9]+)$")


def group_for(name):
    return next((g for g, prefixes in GROUPS.items() if name.startswith(prefixes)), None)


def parse(source):
    definitions = {}
    for line in source.splitlines():
        match = DEFINE.match(line)
        if match and group_for(match[1]):
            definitions[match[1]] = match[2].split("/*")[0].split("//")[0].strip()
    codes = {}

    def evaluate(node):
        if isinstance(node, ast.Constant) and type(node.value) is int:
            return node.value
        if isinstance(node, ast.Name):
            return resolve(node.id)
        if isinstance(node, ast.BinOp):
            a, b = evaluate(node.left), evaluate(node.right)
            if isinstance(node.op, ast.Add): return a + b
            if isinstance(node.op, ast.Sub): return a - b
            if isinstance(node.op, ast.LShift): return a << b
            if isinstance(node.op, ast.BitOr): return a | b
        raise ValueError("Unsupported input constant expression")

    resolving = set()

    def resolve(name):
        if name not in codes:
            if name in resolving:
                raise ValueError("Cyclic input constant: " + name)
            resolving.add(name)
            codes[name] = evaluate(ast.parse(definitions[name], mode="eval").body)
            resolving.remove(name)
        return codes[name]

    for name in definitions:
        resolve(name)
    if "EV_KEY" not in codes or "KEY_A" not in codes:
        raise ValueError("Missing input event definitions")
    labels = {group: {} for group in GROUPS}
    for name, expression in definitions.items():
        # Do not let range/count markers hide real event names.
        if LITERAL.fullmatch(expression) and not name.endswith(("_MAX", "_CNT", "_MIN_INTERESTING")):
            labels[group_for(name)].setdefault(codes[name], name)
    return codes, labels


def native(labels):
    lines = ["// Generated by generate-input.h-labels.py. Do not edit.",
             "#ifndef INPUT_H_LABELS_H", "#define INPUT_H_LABELS_H", "",
             "struct input_label { int value; const char* name; };", ""]
    for group, values in labels.items():
        lines.append(f"static const input_label {group}_labels[] = {{")
        lines.extend(f'    {{{code}, "{name}"}},' for code, name in values.items())
        lines.extend(['    {-1, nullptr}', '};'])
    lines.extend(["", "static inline const char* find_input_label(const input_label* labels, int code) {",
                  "    for (; labels->name != nullptr; ++labels)",
                  "        if (labels->value == code) return labels->name;",
                  "    return nullptr;", "}", "",
                  "static inline const char* get_input_event_label(int type, int code) {",
                  "    switch (type) {"])
    for group in ("syn", "key", "rel", "abs", "sw", "msc", "led", "rep", "snd", "ff_status", "ff"):
        ev = "EV_" + group.upper()
        lines.append(f"        case {ev}: return find_input_label({group}_labels, code);")
    lines.extend(["        default: return nullptr;", "    }", "}", "#endif", ""])
    # This header is self-contained for C++ callers.
    lines.insert(3, "#include <linux/input.h>")
    return "\n".join(lines)


def kotlin_codes(codes):
    lines = ["// Generated by generate-input.h-labels.py. Do not edit.",
             "package xtr.keymapper", "", "object InputEventCodes {"]
    lines.extend(f"    const val {name} = {value}" for name, value in codes.items())
    return "\n".join(lines + ["}", ""])


def kotlin_labels(codes, labels):
    lines = ["// Generated by generate-input.h-labels.py. Do not edit.",
             "package xtr.keymapper", "", "object InputEventLabels {"]
    for group, values in labels.items():
        lines.append(f"    val {group}Labels: Map<Int, String> = mapOf(")
        lines.extend(f'        {code} to "{name}",' for code, name in values.items())
        lines.append("    )")
    lines.append("    fun label(type: Int, code: Int): String? = when (type) {")
    for group in ("syn", "key", "rel", "abs", "sw", "msc", "led", "rep", "snd", "ff_status", "ff"):
        lines.append(f"        InputEventCodes.EV_{group.upper()} -> {group}Labels[code]")
    return "\n".join(lines + ["        else -> null", "    }", "}", ""])


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", nargs="+", type=Path)
    parser.add_argument("--native", type=Path)
    parser.add_argument("--kotlin", type=Path)
    args = parser.parse_args()
    codes, labels = parse("\n".join(p.read_text(encoding="utf-8") for p in args.inputs))
    if args.native:
        write(args.native, native(labels))
    if args.kotlin:
        write(args.kotlin / "xtr/keymapper/InputEventCodes.kt", kotlin_codes(codes))
        write(args.kotlin / "xtr/keymapper/InputEventLabels.kt", kotlin_labels(codes, labels))


if __name__ == "__main__":
    main()
