"""Generate XtMapper's keyboard labels from the NDK input-event-codes.h.

Adapted from AOSP toolbox/generate-input.h-labels.py (android16-qpr2-release).
Like AOSP, only literal definitions are labels, so symbolic aliases do not
replace canonical names. XtMapper consumes KEY_* only, excluding reserved
and range markers; BTN_* codes continue to use its existing button path.
"""

import argparse
from pathlib import Path
import re


DEFINE = re.compile(r"^#define\s+(KEY_\w+)\s+(0[xX][0-9a-fA-F]+|[0-9]+)\s*(?:/\*.*)?$")
EXCLUDED = {"KEY_RESERVED", "KEY_MAX", "KEY_CNT", "KEY_MIN_INTERESTING"}


def generate(source):
    labels = {}
    for line in source.splitlines():
        match = DEFINE.match(line)
        if match and match[1] not in EXCLUDED:
            # First literal name wins for any duplicate values.
            labels.setdefault(int(match[2], 16 if match[2].lower().startswith("0x") else 10), match[1])
    if not labels:
        raise ValueError("No KEY_* labels found in input header")
    lines = [
        "// Generated by generate_linux_key_table.py. Do not edit.",
        "#ifndef LINUX_KEY_TABLE_H",
        "#define LINUX_KEY_TABLE_H",
        "",
        "static inline const char* get_linux_key_name(int code) {",
        "    switch (code) {",
    ]
    lines.extend(f'        case {code}: return "{name}";' for code, name in sorted(labels.items()))
    lines.extend(["        default: return nullptr;", "    }", "}", "", "#endif // LINUX_KEY_TABLE_H", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    content = generate(args.input.read_text(encoding="utf-8"))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
